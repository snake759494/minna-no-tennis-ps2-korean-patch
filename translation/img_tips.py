def bands(a, ylim, xmax):
    sub = a[ylim[0]:ylim[1], :xmax] > 100
    rows = sub.sum(1) >= 2; out = []; y = 0
    while y < len(rows):
        if rows[y]:
            s = y
            while y < len(rows) and (rows[y] or (y + 1 < len(rows) and rows[y + 1]) or (y + 2 < len(rows) and rows[y + 2] and rows[y + 1:y + 3].any())): y += 1
            if y - s >= 8: out.append((s + ylim[0], y + ylim[0]))
        y += 1
    return out
def extent(a, y0, y1, xmax, xs0=0):
    col = (a[y0:y1, :xmax] > 100).any(0); xs = [x for x in range(xs0, xmax) if col[x]]
    if not xs: return None
    s = xs[0]; e = s; gap = 0
    for x in range(s, xmax):
        if col[x]: e = x; gap = 0
        else:
            gap += 1
            if gap > 14: break
    return s, e + 1
def tip(k, lines, align='c', ylim=(0, 256), xmax=512, xcap=None, extra=(), rows=None, path=None, H=256):
    p = path or W + 'L_txt%02d.tm2' % k
    a = tim2.read(open(os.path.join(R, 'work', 'xb', p), 'rb').read())[0]['rgba'][..., 3]
    bs = [(c - 12, c + 12) if isinstance(c, int) else c for c in rows] if rows else bands(a, ylim, xmax)
    if len(bs) != len(lines): DEBUG.append((k, len(bs), len(lines), bs))
    clr, txt = [], []
    for i, ((y0, y1), L) in enumerate(zip(bs, lines)):
        oy0, oy1 = y0, y1
        opts = {}
        if isinstance(L, tuple): L, opts = L
        if y1 - y0 > 27: cy = (y0 + y1) // 2; y0, y1 = cy - 12, cy + 13
        segs = L if isinstance(L, list) else [(L, None, None)]
        for t, sx0, sx1 in segs:
            cap = (xcap[i] if xcap else xmax)
            ex = extent(a, y0, y1, sx1 or cap, sx0 or 0)
            if ex is None: continue
            xs, xe = ex
            if sx0 is not None: xs = sx0
            if sx1 is not None: xe = sx1
            clr.append(dict(cbox=(max(0, xs - 2), max(0, oy0 - 2), min(512, xe + 2), min(H, oy1 + 2)), box=(0, 0, 1, 1), text=''))
            if align == 'c' and sx0 is None:
                cx = (xs + xe) // 2; hw = min(cx, 512 - cx) - 3
                box = (cx - hw, y0 - 1, cx + hw, y1 + 1); al = 'c'
            else:
                box = (xs, y0 - 1, (sx1 or cap) - 2, y1 + 1); al = 'l'
            e = dict(box=box, text=t, align=al, **ST); e.update(opts); txt.append(e)
    SPEC[p] = clr + txt + list(extra)
